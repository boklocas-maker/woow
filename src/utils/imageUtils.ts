function stringHash(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

const GUARANTEED_FALLBACK = 'https://images.unsplash.com/photo-1492684223066-81342ee5ff30?auto=format&fit=crop&w=800&q=80';

/**
 * Returns a high-quality royalty-free image URL for a given category & title/id seed.
 */
export function getFallbackImage(category?: string, seedKey?: string): string {
  const pool = (category && CATEGORY_IMAGE_POOLS[category]) || CATEGORY_IMAGE_POOLS['default'];
  if (!seedKey) {
    return pool[0] || GUARANTEED_FALLBACK;
  }
  const idx = stringHash(seedKey) % pool.length;
  return pool[idx] || GUARANTEED_FALLBACK;
}

/**
 * Helper to ensure a valid image URL for an event, applying category-specific royalty-free image if missing.
 */
export function getEventImage(image?: string | null, category?: string, titleOrSeed?: string): string {
  if (!image || typeof image !== 'string' || image.trim() === '' || image === 'undefined' || image === 'null' || image.includes('photo-1514525253161-7a46d19cd819')) {
    return getFallbackImage(category, titleOrSeed);
  }
  return image;
}

/**
 * Event handler for <img> onError attribute to replace broken or failing images with royalty-free stock photo.
 */
export function handleImageError(
  e: React.SyntheticEvent<HTMLImageElement, Event>,
  category?: string
): void {
  const target = e.currentTarget;
  target.onerror = null;
  target.src = GUARANTEED_FALLBACK;
}

